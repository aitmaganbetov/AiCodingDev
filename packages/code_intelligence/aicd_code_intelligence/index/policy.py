"""Правила включения файлов в индекс (P5-02).

Индексируются только **отслеживаемые** файлы commit (`git ls-tree`), поэтому `.gitignore` соблюдается
неявно. Поверх этого — настраиваемые правила `IndexPolicy`:

* **vendored** (`node_modules/`, `vendor/`, `.venv/`, `dist/`, …) и **oversized** (> `max_file_bytes`,
  размер известен из `ls-tree -l` до чтения) — файл пропускается целиком (не читается, нет строки
  `code_files`); учитывается в статистике;
* symlink (`120000`) и submodule (`160000`) — пропускаются (содержимое вне дерева commit);
* **binary** (NUL в первых 8 KiB или не UTF-8) — строка `code_files` с `is_binary`, без символов/фрагментов;
* **generated** (lock-файлы, `*.min.js`, `*_pb2.py`, маркер `@generated`/`DO NOT EDIT` в начале файла) —
  строка `code_files` с `is_generated`, без символов/фрагментов.
"""

from __future__ import annotations

import fnmatch
import re
from dataclasses import dataclass
from enum import StrEnum
from pathlib import PurePosixPath

DEFAULT_VENDORED_DIRS: frozenset[str] = frozenset(
    {
        "node_modules",
        "bower_components",
        "vendor",
        "third_party",
        ".venv",
        "venv",
        "__pycache__",
        ".mypy_cache",
        ".pytest_cache",
        ".ruff_cache",
        ".tox",
        ".git",
        "dist",
        "build",
        ".next",
        ".nuxt",
        "coverage",
        "site-packages",
    }
)

DEFAULT_GENERATED_GLOBS: tuple[str, ...] = (
    "*.min.js",
    "*.min.css",
    "*.map",
    "*_pb2.py",
    "*_pb2_grpc.py",
    "*.pb.go",
    "*.generated.*",
    "*.g.dart",
    "package-lock.json",
    "npm-shrinkwrap.json",
    "yarn.lock",
    "pnpm-lock.yaml",
    "poetry.lock",
    "uv.lock",
    "Pipfile.lock",
    "composer.lock",
    "Cargo.lock",
    "go.sum",
)

_GENERATED_MARKER = re.compile(
    rb"@generated|do not edit|auto-generated|autogenerated", re.IGNORECASE
)
_GENERATED_HEAD_BYTES = 1024
_BINARY_PROBE_BYTES = 8192

_TEST_DIRS = frozenset({"tests", "test", "__tests__", "spec", "specs"})
_TEST_NAME = re.compile(
    r"^(test_.+\.py|.+_test\.py|conftest\.py|.+\.(test|spec)\.(js|jsx|ts|tsx|mjs|cjs|mts|cts)|.+Test\.php)$"
)


class SkipReason(StrEnum):
    VENDORED = "vendored"
    OVERSIZED = "oversized"
    SYMLINK = "symlink"
    SUBMODULE = "submodule"
    EXCLUDED = "excluded"


@dataclass(frozen=True)
class IndexPolicy:
    """Настраиваемые правила. Значения по умолчанию рассчитаны на исходный код, а не на данные."""

    max_file_bytes: int = 1024 * 1024
    vendored_dirs: frozenset[str] = DEFAULT_VENDORED_DIRS
    generated_globs: tuple[str, ...] = DEFAULT_GENERATED_GLOBS
    exclude_globs: tuple[str, ...] = ()  # дополнительные исключения проекта (по полному пути)
    max_files: int = 200_000
    chunk_lines: int = 120  # окно фрагмента `code_file`
    max_symbol_chunk_lines: int = 400  # больший символ режется на окна

    def skip_reason(self, path: str, mode: str, size: int | None) -> SkipReason | None:
        if mode == "120000":
            return SkipReason.SYMLINK
        if mode == "160000":
            return SkipReason.SUBMODULE
        parts = PurePosixPath(path).parts
        if any(part in self.vendored_dirs for part in parts[:-1]):
            return SkipReason.VENDORED
        if any(fnmatch.fnmatchcase(path, pattern) for pattern in self.exclude_globs):
            return SkipReason.EXCLUDED
        if size is not None and size > self.max_file_bytes:
            return SkipReason.OVERSIZED
        return None

    def is_generated_name(self, path: str) -> bool:
        name = PurePosixPath(path).name
        return any(fnmatch.fnmatchcase(name, pattern) for pattern in self.generated_globs)


def is_binary(content: bytes) -> bool:
    if b"\x00" in content[:_BINARY_PROBE_BYTES]:
        return True
    try:
        content.decode("utf-8")
    except UnicodeDecodeError:
        return True
    return False


def has_generated_marker(content: bytes) -> bool:
    return _GENERATED_MARKER.search(content[:_GENERATED_HEAD_BYTES]) is not None


def is_test_path(path: str) -> bool:
    p = PurePosixPath(path)
    return bool(_TEST_NAME.match(p.name)) or any(part in _TEST_DIRS for part in p.parts[:-1])
