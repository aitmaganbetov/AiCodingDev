export type IconName = keyof typeof ICONS;
export const ICON_NAMES = Object.keys(ICONS) as IconName[];

export interface IconProps extends Omit<SVGProps<SVGSVGElement>, 'ref'> {
  name: IconName;
  /** Анимация вращения (индикатор «выполняется»); отключается при prefers-reduced-motion. */
  spin?: boolean;
}

export function Icon({ name, className = 'h-5 w-5', spin = false, ...rest }: IconProps) {
  const Glyph = ICONS[name];
  return (
    <Glyph
      aria-hidden="true"
      focusable="false"
      strokeWidth={1.75}
      className={[className, spin ? 'motion-safe:animate-spin' : ''].filter(Boolean).join(' ')}
      data-icon={name}
      {...rest}
    />
  );
}
