"""P5-02: построение снимка по commit без БД — дерево `git ls-tree`, исключения, инкрементальность.

Критерий бэклога «повторная индексация меняет только изменённые файлы» проверяется счётчиками работы
`IndexStats` (прочитанные blob, разобранные файлы) — переиспользованные файлы не читаются и не разбираются.
"""

