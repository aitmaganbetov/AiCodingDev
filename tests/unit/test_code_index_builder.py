def by_path(build: SnapshotBuild) -> dict[str, object]:
    return {f.path: f for f in build.files}


def previous_of(build: SnapshotBuild) -> dict[str, PreviousFile]:
    """Состояние «предыдущего снимка» так, как его загрузил бы store.load_previous."""
    out = {}
    for f in build.files:
        module = None
        if f.analysis is not None:
            module = f.analysis.symbols[0].qualified_name
        elif f.reused_from is not None:
            module = f.reused_from.module_name
        out[f.path] = PreviousFile(
            file_id=None,
            path=f.path,
            blob_sha=f.blob_sha,
            content_hash=f.content_hash,
            size_bytes=f.size_bytes,
            language=f.language,
            is_test=f.is_test,
            is_generated=f.is_generated,
            is_binary=f.is_binary,
            module_name=module,
            imports=f.imports,
            declared=f.declared,
        )
    return out


def test_full_build_exclusions_and_flags(repo: Path) -> None:
    sha = git(repo, "rev-parse", "HEAD")
    build = build_snapshot(repo, sha, policy=IndexPolicy(max_file_bytes=1000))
    files = by_path(build)
    assert "ignored.py" not in files  # .gitignore соблюдается неявно (только отслеживаемые файлы)
    assert "node_modules/pkg/index.js" not in files
    assert "vendor/autoload.php" not in files
    assert "link" not in files
    assert "big.sql" not in files  # oversized
    assert build.stats.skipped == {"oversized": 1, "symlink": 1, "vendored": 2}
    png = files["logo.png"]
    assert png.is_binary and png.analysis is None and png.chunks == []  # type: ignore[attr-defined]
    for generated in ("package-lock.json", "gen/api_pb2.py", "gen/client.py"):
        assert files[generated].is_generated and files[generated].analysis is None  # type: ignore[attr-defined]
    core = files["src/app/core.py"]
    assert core.analysis.symbols[0].qualified_name == "app.core"  # type: ignore[attr-defined]
    assert files["tests/test_core.py"].is_test  # type: ignore[attr-defined]
    edges = {(e.edge_type, e.source_path, e.target_path) for e in build.edges}
    assert ("imports", "src/app/core.py", "src/app/util.py") in edges
    assert ("imports", "tests/test_core.py", "src/app/core.py") in edges
    assert ("tests", "tests/test_core.py", "src/app/core.py") in edges
    assert ("imports", "web/index.ts", "web/lib.ts") in edges
    assert build.stats.files_reused == 0
    assert build.stats.blobs_read == len(build.files)


def test_incremental_rebuild_touches_only_changed_files(repo: Path) -> None:
    first_sha = git(repo, "rev-parse", "HEAD")
    first = build_snapshot(repo, first_sha)
    parsed_first = first.stats.files_parsed
    assert parsed_first >= 7

    write(repo, "src/app/util.py", "def helper() -> int:\n    return 2\n")  # изменён
    write(repo, "src/app/extra.py", "VALUE = 1\n")  # добавлен
    (repo / "README.md").unlink()  # удалён
    second_sha = commit(repo, "change")
    second = build_snapshot(repo, second_sha, previous=previous_of(first))

    assert second.stats.blobs_read == 2  # читаются только изменённый и новый файлы
    assert second.stats.files_parsed == 2
    assert second.stats.files_reused == len(second.files) - 2
    files = by_path(second)
    assert "README.md" not in files
    assert files["src/app/util.py"].reused_from is None  # type: ignore[attr-defined]
    assert files["src/app/core.py"].reused_from is not None  # type: ignore[attr-defined]
    # импорты переиспользованного файла разрешаются заново против нового набора файлов
    edges = {(e.edge_type, e.source_path, e.target_path) for e in second.edges}
    assert ("imports", "src/app/core.py", "src/app/util.py") in edges

    # Без изменений — ничего не читается и не разбирается.
    third = build_snapshot(repo, second_sha, previous=previous_of(second))
    assert third.stats.blobs_read == 0
    assert third.stats.files_parsed == 0
    assert [(e.edge_type, e.source_path, e.target_path, e.target_ref) for e in third.edges] == [
        (e.edge_type, e.source_path, e.target_path, e.target_ref) for e in second.edges
    ]


def test_python_module_rename_invalidates_reuse(repo: Path) -> None:
    first = build_snapshot(repo, git(repo, "rev-parse", "HEAD"))
    (repo / "src/app/__init__.py").unlink()  # пакет исчез: имена модулей изменились
    sha = commit(repo, "drop init")
    second = build_snapshot(repo, sha, previous=previous_of(first))
    core = by_path(second)["src/app/core.py"]
    assert core.reused_from is None  # type: ignore[attr-defined]
    assert core.analysis.symbols[0].qualified_name == "core"  # type: ignore[attr-defined]


def test_rejects_bad_commit_and_missing_objects(repo: Path) -> None:
    with pytest.raises(GitSourceError):
        list_tree(repo, "--output=/tmp/x")
    with pytest.raises(GitSourceError):
        list_tree(repo, "HEAD")
    with pytest.raises(GitSourceError):
        list_tree(repo, "0" * 40)


def test_tree_parsing_drops_unsafe_paths() -> None:
    sha = "a" * 40
    raw = b"".join(
        f"100644 blob {sha} 3\t{p}".encode() + b"\x00"
        for p in ["ok.py", "../escape.py", "/abs.py", "a/./b.py", "dir/../x", "tab\tname"]
    ) + b"100644 blob " + sha.encode() + b" 3\tctl\x01.py\x00"
    entries, unsafe = parse_ls_tree(raw)
    assert [e.path for e in entries] == ["ok.py"]
    assert "../escape.py" in unsafe and "/abs.py" in unsafe and "ctl\x01.py" in unsafe
    assert not is_safe_tree_path("a\\b")
    assert not is_safe_tree_path("x/../../etc")


def test_cat_file_batch_parsing_is_strict() -> None:
    sha = "b" * 40
    assert parse_cat_file_batch(f"{sha} blob 3\nabc\n".encode(), [sha]) == {sha: b"abc"}
    with pytest.raises(GitSourceError):
        parse_cat_file_batch(f"{sha} blob 10\nabc\n".encode(), [sha])
    with pytest.raises(GitSourceError):
        parse_cat_file_batch(f"{sha} missing\n".encode(), [sha])


def test_read_blobs_does_not_apply_filters(repo: Path, tmp_path: Path) -> None:
    # Фильтр smudge в конфигурации недоверенного репозитория не исполняется при чтении blob.
    marker = tmp_path / "pwned"
    git(repo, "config", "filter.evil.smudge", f"touch {marker}; cat")
    write(repo, ".gitattributes", "*.py filter=evil\n")
    sha = commit(repo, "attrs")
    entries, _ = list_tree(repo, sha)
    blobs = read_blobs(repo, entries)
    assert blobs
    build_snapshot(repo, sha)
    assert not marker.exists()
